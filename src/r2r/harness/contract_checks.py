"""Contract checks (D88): interfaces, documented errors and output files, described as data.

The designer lists `MathSpec.contract_checks`; this module renders them into a frozen pytest file
from a fixed template (no test code written by a model) plus a small runtime helper. They then
run like every frozen check: red on the stubs (their NotImplementedError propagates), green on
the reference, read-only to the coder. Interface checks pass on stubs by design: the stubs
already carry the final signatures.
"""

from __future__ import annotations

import json
from collections.abc import Sequence
from pathlib import Path

from r2r.contracts import ContractCheck
from r2r.contracts.math import CONTRACT_DIR

LIB_NAME = "contract_lib_v1.py"  # versioned: a frozen copy from an older run is never rewritten

LIB = '''"""Runtime helper for generated contract checks (r2r, D88). Do not edit."""

import builtins
import csv
import importlib
import inspect
import json
import re
import tempfile
from pathlib import Path

import numpy as np

PNG = b"\\x89PNG\\r\\n\\x1a\\n"
_TOKEN = re.compile(r"([^.\\[\\]]+)|\\[(\\d+)\\]")


def resolve(path):
    """`pkg.mod.name.attr`: import the longest module prefix, then walk attributes."""
    parts = path.split(".")
    for i in range(len(parts) - 1, 0, -1):
        module = ".".join(parts[:i])
        try:
            obj = importlib.import_module(module)
        except ModuleNotFoundError as e:
            if e.name and not module.startswith(e.name):
                raise  # the module exists but one of its own imports is missing
            continue
        for name in parts[i:]:
            obj = getattr(obj, name)
        return obj
    raise AssertionError(f"cannot import {path}")


def exception(name):
    return getattr(builtins, name) if "." not in name else resolve(name)


def build(value, tmp):
    if isinstance(value, str):
        return value.replace("{tmp}", tmp)
    if isinstance(value, dict):
        if set(value) == {"np"}:
            return np.asarray(build(value["np"], tmp))
        return {k: build(v, tmp) for k, v in value.items()}
    if isinstance(value, list):
        return [build(v, tmp) for v in value]
    return value


def field(data, path):
    cur = data
    for name, index in _TOKEN.findall(path):
        cur = cur[name] if name else cur[int(index)]
    return cur


def invoke(c, tmp):
    result = resolve(c["call"])(**build(c["args"], tmp))
    if c["method"]:
        result = getattr(result, c["method"])(**build(c["method_args"], tmp))
    return result


def run_check(c):
    tmp = tempfile.mkdtemp(prefix="contract-")
    kind, call = c["kind"], c["call"]
    if kind == "interface":
        params = inspect.signature(resolve(call)).parameters
        found = [p for p in params if p not in ("self", "cls")]
        assert found == c["params"], f"params of {call}: expected {c['params']}, found {found}"
        return
    if kind == "raises":
        expected = exception(c["raises"])
        try:
            invoke(c, tmp)
        except NotImplementedError:
            raise  # a stub: fails for the right reason
        except expected:
            return
        except Exception as e:
            raise AssertionError(
                f"{call} raised {type(e).__name__}: {e}; expected {c['raises']}"
            ) from e
        raise AssertionError(f"{call} did not raise {c['raises']}")
    invoke(c, tmp)
    path = Path(c["file"].replace("{tmp}", tmp))
    assert path.is_file() and path.stat().st_size > 0, f"{c['file']} was not written by {call}"
    fmt = c["format"]
    if fmt == "png":
        assert path.read_bytes()[:8] == PNG, f"{c['file']} is not a png"
    elif fmt == "npy":
        try:
            np.load(path, allow_pickle=False)
        except ValueError as e:
            raise AssertionError(f"{c['file']} is not a npy array: {e}") from e
    elif fmt == "txt":
        assert path.read_text().strip(), f"{c['file']} is empty"
    elif fmt == "csv":
        with path.open(newline="") as fh:
            header = next(csv.reader(fh), [])
        missing = [k for k in c["keys"] if k not in header]
        assert not missing, f"{c['file']}: missing columns {missing}"
    else:  # json
        try:
            data = json.loads(path.read_text())
        except ValueError as e:
            raise AssertionError(f"{c['file']} is not valid json: {e}") from e
        for key in c["keys"]:
            try:
                field(data, key)
            except (KeyError, IndexError, TypeError):
                raise AssertionError(f"{c['file']}: missing key {key}") from None
'''

TEMPLATE = '''"""Generated by r2r from the contract_checks of {mid} (D88). Do not edit."""

import json

from {lib} import run_check

CHECKS = json.loads({payload!r})
{tests}'''


def contract_file(milestone_id: str) -> str:
    return f"{CONTRACT_DIR}/test_contract_{milestone_id.lower()}.py"


def render(milestone_id: str, checks: Sequence[ContractCheck]) -> str:
    data = {
        c.id: c.model_dump(mode="json")
        | {"args": c.args_dict(), "method_args": c.method_args_dict()}
        for c in checks
    }
    payload = json.dumps(data, sort_keys=True)
    tests = "".join(
        f"\n\ndef test_{cid}__{c.id}_{c.kind}():\n    run_check(CHECKS[{c.id!r}])\n"
        for c in checks
        for cid in c.criterion_ids
    )
    lib = LIB_NAME.removesuffix(".py")
    return TEMPLATE.format(mid=milestone_id, lib=lib, payload=payload, tests=tests)


def write_contract_tests(
    root: Path, milestone_id: str, checks: Sequence[ContractCheck]
) -> str | None:
    """Write the milestone's generated file (and the helper once); None when it has no checks."""
    if not checks:
        return None
    folder = root / CONTRACT_DIR
    folder.mkdir(parents=True, exist_ok=True)
    lib = folder / LIB_NAME
    if not lib.exists():
        lib.write_text(LIB)
    rel = contract_file(milestone_id)
    (root / rel).write_text(render(milestone_id, checks))
    return rel
